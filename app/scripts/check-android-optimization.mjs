/** Fail release validation if the Play bundle lacks R8 reports needed for auditing/retrace. */
import { execFileSync } from "node:child_process";
import { resolve } from "node:path";

const bundle = resolve(process.argv[2] ?? "android/app/build/outputs/bundle/release/app-release.aab");
const entries = execFileSync("unzip", ["-Z1", bundle], { encoding: "utf8" }).split("\n");
const mapping = entries.find((name) => name.endsWith("/proguard.map"));
if (!mapping) throw new Error("Release bundle has no R8 mapping; code optimization/retrace metadata is missing");
const text = execFileSync("unzip", ["-p", bundle, mapping], { encoding: "utf8", maxBuffer: 32 * 1024 * 1024 });
if (!text.includes("# compiler: R8")) throw new Error("Release mapping was not generated by R8");
console.log("Release bundle contains R8 mapping metadata");

const reportPath = entries.find((name) => name === "BUNDLE-METADATA/com.android.tools/r8.json");
if (!reportPath) throw new Error("Release bundle has no R8 optimization report for Play");
const report = JSON.parse(execFileSync("unzip", ["-p", bundle, reportPath], { encoding: "utf8" }));
for (const option of ["isObfuscationEnabled", "isOptimizationsEnabled", "isShrinkingEnabled"]) {
  if (report.options[option] !== true) throw new Error(`R8 release option disabled: ${option}`);
}
if (report.options.isDebugModeEnabled !== false) throw new Error("R8 release was built in debug mode");
if (!report.resourceOptimization.isOptimizedShrinkingEnabled) throw new Error("Optimized resource shrinking is disabled");
console.log("Release R8 optimization, shrinking, obfuscation and resource reporting verified");

for (const [field, label] of [
  ["noOptimizationPercentage", "Optimization"],
  ["noShrinkingPercentage", "Shrinking"],
  ["noObfuscationPercentage", "Obfuscation"],
]) {
  const excluded = report.stats[field];
  if (!Number.isFinite(excluded) || excluded < 0 || excluded > 100) {
    throw new Error(`Invalid R8 coverage statistic: ${field}`);
  }
  console.log(`${label} coverage: ${(100 - excluded).toFixed(2)}%`);
}
